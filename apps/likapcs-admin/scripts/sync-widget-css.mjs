#!/usr/bin/env node
/**
 * Mirrors the client's countdown-widget CSS (apps/likapcs-client/src/styles.css, the `.overlay`
 * block) into Admin's stylesheet as `.wm` mock-up rules, between the markers
 * `@widget-mock-start` / `@widget-mock-end` in src/styles/app.css.
 *
 * Settings › Client screen draws the thirteen designs with these rules (WidgetMock.tsx), so the
 * gallery and the desktop preview always look exactly like the PC. Run after changing the widget:
 *   node apps/likapcs-admin/scripts/sync-widget-css.mjs        (writes)
 *   node apps/likapcs-admin/scripts/sync-widget-css.mjs --check (CI: fails when out of date)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const clientCss = resolve(here, '../../likapcs-client/src/styles.css');
const adminCss = resolve(here, '../src/styles/app.css');
const START = '/* @widget-mock-start */';
const END = '/* @widget-mock-end */';

const client = readFileSync(clientCss, 'utf8');
const from = client.indexOf('/* ─── Overlay (countdown widget)');
const to = client.indexOf('/* ─── Lock-screen product slideshow', from);
if (from < 0 || to < 0) throw new Error('client widget CSS block not found');
let block = client.slice(from, to);

// browser-dev-mode rules only make sense in the client
block = block.replace(/\/\* Browser\/dev mode:[\s\S]*?(?=\n\/\* ── shared pieces ── \*\/)/, '');
// the mock is an in-flow box, not the window
block = block.replace(
  `  position: fixed;
  inset: 0;
  display: flex;
  flex-direction: column;
  padding: 10px 14px 0;`,
  `  position: relative;
  flex: none;
  box-sizing: border-box;
  display: flex;
  flex-direction: column;
  padding: 10px 14px 0;
  --border: #1f2937;
  --accent: #6366f1;
  --accent-2: #22d3ee;
  --muted: #94a3b8;
  --warning: #f59e0b;
  color-scheme: dark;
  font-family: inherit;
  text-align: left;
  line-height: normal;`,
);
block = block.replace('.overlay:active {\n  cursor: grabbing;\n}\n', '');
block = block.replace('cursor: grab;\n', 'cursor: default;\n');
block = block.replace(/html\[data-widget-pos\$='left'\] /g, '.wm--left ');
block = block
  .replace(/overlay__/g, 'wm__')
  .replace(/overlay--/g, 'wm--')
  .replace(/\.overlay/g, '.wm');
block = block
  .replace(/overlay-alarm/g, 'wm-alarm')
  .replace(/strip-run/g, 'wm-strip-run')
  .replace(/pin-in/g, 'wm-pin-in')
  .replace(/animation: pulse /g, 'animation: wm-pulse ');
// the gallery reveals the tray while the card is hovered
block = block.replace(
  '.wm.is-revealed .wm__tray {',
  '.wd-card:hover .wm__tray,\n.wm.is-revealed .wm__tray {',
);
block = block.replace(
  '.wm.is-revealed .wm__act {',
  '.wd-card:hover .wm__act,\n.wm.is-revealed .wm__act {',
);
block = block.replace(
  /\/\* ─── Overlay \(countdown widget\)[^\n]*\n(\/\*[\s\S]*?\*\/\n)?/,
  `/* ─── Widget design mock-ups (Settings › Client screen, 0.13.0) ──────────────────
   GENERATED by scripts/sync-widget-css.mjs from the client's widget CSS
   (apps/likapcs-client/src/styles.css, \`.overlay\`): same structure with the \`.wm\` prefix,
   drawn at the real footprint and scaled down by WidgetMock. Do not edit by hand. */
`,
);
block += `@keyframes wm-pulse {
  0%,
  100% {
    opacity: 1;
  }
  50% {
    opacity: 0.45;
  }
}
`;

const admin = readFileSync(adminCss, 'utf8');
const a = admin.indexOf(START);
const b = admin.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing in admin app.css');
const next = `${admin.slice(0, a + START.length)}\n${block.trimEnd()}\n${admin.slice(b)}`;
if (process.argv.includes('--check')) {
  if (next !== admin) {
    console.error(
      'admin widget mock CSS is out of date — run node apps/likapcs-admin/scripts/sync-widget-css.mjs',
    );
    process.exit(1);
  }
  console.info('widget mock CSS up to date');
} else if (next !== admin) {
  writeFileSync(adminCss, next);
  console.info('widget mock CSS updated');
} else {
  console.info('widget mock CSS unchanged');
}
